//! PostgreSQL export: a **psql-restorable** dump of the `public` schema.
//!
//! The output is what `pg_dump --schema-only` + `COPY … TO STDOUT` would
//! produce, assembled by hand from `pg_catalog` so no `pg_dump` binary is
//! needed on the hub host:
//!
//! 1. header + `SET` session safety (`search_path`, encoding, strings),
//! 2. enum types, sequences, tables (with defaults, NOT NULL, identity),
//! 3. `COPY … FROM stdin` data blocks (the server itself renders each row
//!    through `COPY (SELECT …) TO STDOUT WITH (FORMAT text)`, streamed chunk
//!    by chunk — see [`sqlx::postgres::PgPoolCopyExt::copy_out_raw`]),
//! 4. constraints and indexes (after the data, so FKs restore in any order),
//! 5. sequence values (`setval`).
//!
//! The whole export is streamed into a gzip encoder ([`flate2`]): at most one
//! server chunk plus the encoder buffers are in memory at a time; the caller
//! receives the compressed artifact.

use std::io::Write;

use flate2::write::GzEncoder;
use flate2::Compression;
use sqlx::postgres::PgPoolCopyExt;
use sqlx::PgPool;
use tokio_stream::StreamExt;

use super::BackupError;

/// One table of the dump.
struct Table {
    name: String,
    columns: Vec<Column>,
}

struct Column {
    name: String,
    /// `format_type()` rendering (e.g. `character varying(512)`, `jsonb`).
    type_name: String,
    not_null: bool,
    default: Option<String>,
    /// `a`/`d` for `GENERATED ALWAYS/BY DEFAULT AS IDENTITY`, `''` otherwise.
    identity: String,
    /// `s` for a stored generated column, `''` otherwise.
    generated: String,
}

/// Export the `public` schema as a gzip-compressed SQL script.
pub async fn export_gzip(pool: &PgPool) -> Result<Vec<u8>, BackupError> {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
    export_sql(pool, &mut encoder).await?;
    encoder
        .finish()
        .map_err(|e| BackupError::Export(format!("gzip: {e}")))
}

/// Export the `public` schema as a plain SQL script into `out`.
pub async fn export_sql<W: Write + Send>(pool: &PgPool, out: &mut W) -> Result<(), BackupError> {
    fn write<W: Write>(out: &mut W, text: &str) -> Result<(), BackupError> {
        out.write_all(text.as_bytes())
            .map_err(|e| BackupError::Export(format!("write: {e}")))
    }

    write(
        out,
        "-- huginn-hub database dump (restorable with psql -f or psql < file)\n\
         -- generated by huginn-hub services/backup\n",
    )?;
    write(
        out,
        "SET client_encoding = 'UTF8';\n\
         SET standard_conforming_strings = on;\n\
         SELECT pg_catalog.set_config('search_path', 'public, pg_catalog', false);\n\
         BEGIN;\n\n",
    )?;

    // -- enum types ---------------------------------------------------------
    let types = enum_types(pool).await?;
    let mut current_type = String::new();
    let mut labels: Vec<String> = Vec::new();
    fn flush<W: Write>(out: &mut W, name: &str, labels: &[String]) -> Result<(), BackupError> {
        if name.is_empty() {
            return Ok(());
        }
        let quoted: Vec<String> = labels.iter().map(|l| quote_literal(l)).collect();
        write(
            out,
            &format!(
                "CREATE TYPE {} AS ENUM ({});\n",
                quote_ident(name),
                quoted.join(", ")
            ),
        )
    }
    for (type_name, label) in types {
        if type_name != current_type {
            flush(out, &current_type, &labels)?;
            current_type = type_name;
            labels.clear();
        }
        labels.push(label);
    }
    flush(out, &current_type, &labels)?;
    write(out, "\n")?;

    // -- sequences ----------------------------------------------------------
    let sequences = sequence_defs(pool).await?;
    for (name, seq_type, start, increment, min, max, cache, cycle) in &sequences {
        write(
            out,
            &format!(
                "CREATE SEQUENCE {} AS {} START WITH {} INCREMENT BY {} {} {} CACHE {}{};\n",
                quote_ident(name),
                seq_type,
                start,
                increment,
                limit("MINVALUE", *min),
                limit("MAXVALUE", *max),
                cache,
                if *cycle { " CYCLE" } else { " NO CYCLE" },
            ),
        )?;
    }
    write(out, "\n")?;

    // -- tables -------------------------------------------------------------
    let tables = table_defs(pool).await?;
    for table in &tables {
        write(
            out,
            &format!("CREATE TABLE {} (\n", quote_ident(&table.name)),
        )?;
        for (index, column) in table.columns.iter().enumerate() {
            let mut line = format!("    {} {}", quote_ident(&column.name), column.type_name);
            if column.generated == "s" {
                line.push_str(&format!(
                    " GENERATED ALWAYS AS ({}) STORED",
                    column.default.as_deref().unwrap_or("NULL")
                ));
            } else {
                if let Some(default) = &column.default {
                    line.push_str(&format!(" DEFAULT {default}"));
                }
                match column.identity.as_str() {
                    "a" => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
                    "d" => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
                    _ => {}
                }
            }
            if column.not_null {
                line.push_str(" NOT NULL");
            }
            line.push(if index + 1 == table.columns.len() {
                '\n'
            } else {
                ','
            });
            if index + 1 != table.columns.len() {
                line.push('\n');
            }
            write(out, &line)?;
        }
        write(out, ");\n")?;
    }
    write(out, "\n")?;

    // -- sequence ownership -------------------------------------------------
    for (sequence, table, column) in sequence_ownerships(pool).await? {
        write(
            out,
            &format!(
                "ALTER SEQUENCE {} OWNED BY {}.{};\n",
                quote_ident(&sequence),
                quote_ident(&table),
                quote_ident(&column)
            ),
        )?;
    }
    write(out, "\n")?;

    // -- data ---------------------------------------------------------------
    for table in &tables {
        let columns: Vec<String> = table.columns.iter().map(|c| quote_ident(&c.name)).collect();
        write(
            out,
            &format!(
                "COPY {} ({}) FROM stdin;\n",
                quote_ident(&table.name),
                columns.join(", ")
            ),
        )?;
        let statement = format!(
            "COPY (SELECT {} FROM {}) TO STDOUT WITH (FORMAT text)",
            columns.join(", "),
            quote_ident(&table.name)
        );
        // Stream the server-rendered COPY text straight through: no row is
        // materialized client-side.
        let mut stream = pool
            .copy_out_raw(&statement)
            .await
            .map_err(|e| BackupError::Export(format!("COPY {}: {e}", table.name)))?;
        while let Some(chunk) = stream.next().await {
            let chunk =
                chunk.map_err(|e| BackupError::Export(format!("COPY {}: {e}", table.name)))?;
            out.write_all(&chunk)
                .map_err(|e| BackupError::Export(format!("write: {e}")))?;
        }
        write(out, "\\.\n")?;
    }
    write(out, "\n")?;

    // -- indexes (those not backing a constraint) ---------------------------
    // Before the constraints: a foreign key may reference a plain unique
    // index, and constraint-backed indexes are created by ADD CONSTRAINT.
    let constraint_rows = constraints(pool).await?;
    let constraint_names: std::collections::HashSet<String> =
        constraint_rows.iter().map(|(_, n, _)| n.clone()).collect();
    for (name, definition) in indexes(pool).await? {
        if constraint_names.contains(&name) {
            continue;
        }
        write(out, &format!("{definition};\n"))?;
    }
    write(out, "\n")?;

    // -- constraints (after data + indexes: PK/UNIQUE, CHECK, then FKs) ----
    for (table, name, definition) in &constraint_rows {
        write(
            out,
            &format!(
                "ALTER TABLE ONLY {} ADD CONSTRAINT {} {};\n",
                quote_ident(table),
                quote_ident(name),
                definition
            ),
        )?;
    }
    write(out, "\n")?;

    // -- sequence values ----------------------------------------------------
    if let Ok(values) = sequence_values(pool).await {
        for (name, last) in values {
            if let Some(last) = last {
                write(
                    out,
                    &format!(
                        "SELECT pg_catalog.setval('{}', {}, true);\n",
                        quote_ident(&name),
                        last
                    ),
                )?;
            }
        }
    }
    write(out, "\nCOMMIT;\n")?;
    Ok(())
}

/// `NO MINVALUE` / `MINVALUE n` (and MAXVALUE) like pg_dump renders them.
fn limit(kind: &str, value: i64) -> String {
    let sentinel = if kind == "MINVALUE" {
        i64::MIN
    } else {
        i64::MAX
    };
    if value == sentinel {
        format!("NO {kind}")
    } else {
        format!("{kind} {value}")
    }
}

/// Double-quote an identifier when it is not a bare lowercase name.
pub fn quote_ident(name: &str) -> String {
    let bare = !name.is_empty()
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        && !name.as_bytes()[0].is_ascii_digit();
    if bare {
        name.to_owned()
    } else {
        format!("\"{}\"", name.replace('"', "\"\""))
    }
}

/// Single-quote a string literal.
pub fn quote_literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

// ---------------------------------------------------------------------------
// pg_catalog queries (only the `public` schema is dumped)
// ---------------------------------------------------------------------------

async fn enum_types(pool: &PgPool) -> Result<Vec<(String, String)>, BackupError> {
    let rows: Vec<(String, String)> = sqlx::query_as(
        "SELECT t.typname, e.enumlabel \
         FROM pg_catalog.pg_type t \
         JOIN pg_catalog.pg_enum e ON e.enumtypid = t.oid \
         JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace \
         WHERE n.nspname = 'public' \
         ORDER BY t.typname, e.enumsortorder",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog types: {e}")))?;
    Ok(rows)
}

type SequenceDef = (String, String, i64, i64, i64, i64, i64, bool);

async fn sequence_defs(pool: &PgPool) -> Result<Vec<SequenceDef>, BackupError> {
    let rows: Vec<SequenceDef> = sqlx::query_as(
        "SELECT c.relname, s.seqtypid::regtype::text, s.seqstart, s.seqincrement, \
         s.seqmin, s.seqmax, s.seqcache, s.seqcycle \
         FROM pg_catalog.pg_class c \
         JOIN pg_catalog.pg_sequence s ON s.seqrelid = c.oid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         WHERE n.nspname = 'public' \
         ORDER BY c.relname",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog sequences: {e}")))?;
    Ok(rows)
}

async fn sequence_ownerships(pool: &PgPool) -> Result<Vec<(String, String, String)>, BackupError> {
    let rows: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT seq.relname, tbl.relname, att.attname \
         FROM pg_catalog.pg_class seq \
         JOIN pg_catalog.pg_depend dep ON dep.objid = seq.oid \
             AND dep.classid = 'pg_catalog.pg_class'::regclass \
             AND dep.refclassid = 'pg_catalog.pg_class'::regclass AND dep.deptype = 'a' \
         JOIN pg_catalog.pg_class tbl ON tbl.oid = dep.refobjid \
         JOIN pg_catalog.pg_attribute att ON att.attrelid = dep.refobjid \
             AND att.attnum = dep.refobjsubid \
         JOIN pg_catalog.pg_namespace n ON n.oid = seq.relnamespace \
         WHERE n.nspname = 'public' AND seq.relkind = 'S' \
         ORDER BY seq.relname",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog sequence owners: {e}")))?;
    Ok(rows)
}

async fn sequence_values(pool: &PgPool) -> Result<Vec<(String, Option<i64>)>, BackupError> {
    let rows: Vec<(String, Option<i64>)> = sqlx::query_as(
        "SELECT c.relname, pg_catalog.pg_sequence_last_value(c.oid) \
         FROM pg_catalog.pg_class c \
         JOIN pg_catalog.pg_sequence s ON s.seqrelid = c.oid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         WHERE n.nspname = 'public' \
         ORDER BY c.relname",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog sequence values: {e}")))?;
    Ok(rows)
}

/// One `pg_attribute` row: name, type, not-null, default, identity, generated.
type ColumnRow = (String, String, String, bool, Option<String>, String, String);

async fn table_defs(pool: &PgPool) -> Result<Vec<Table>, BackupError> {
    let rows: Vec<ColumnRow> = sqlx::query_as(
        "SELECT c.relname, a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod), \
         a.attnotnull, pg_catalog.pg_get_expr(d.adbin, d.adrelid), \
         a.attidentity::text, a.attgenerated::text \
         FROM pg_catalog.pg_class c \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         JOIN pg_catalog.pg_attribute a ON a.attrelid = c.oid \
         LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
         WHERE n.nspname = 'public' AND c.relkind = 'r' \
           AND a.attnum > 0 AND NOT a.attisdropped \
         ORDER BY c.relname, a.attnum",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog tables: {e}")))?;

    let mut tables: Vec<Table> = Vec::new();
    for (table, column, type_name, not_null, default, identity, generated) in rows {
        let entry = match tables.last_mut() {
            Some(last) if last.name == table => last,
            _ => {
                tables.push(Table {
                    name: table,
                    columns: Vec::new(),
                });
                tables.last_mut().unwrap()
            }
        };
        entry.columns.push(Column {
            name: column,
            type_name,
            not_null,
            default,
            identity,
            generated,
        });
    }
    Ok(tables)
}

async fn constraints(pool: &PgPool) -> Result<Vec<(String, String, String)>, BackupError> {
    let rows: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT rel.relname, con.conname, pg_catalog.pg_get_constraintdef(con.oid) \
         FROM pg_catalog.pg_constraint con \
         JOIN pg_catalog.pg_class rel ON rel.oid = con.conrelid \
         JOIN pg_catalog.pg_namespace n ON n.oid = rel.relnamespace \
         WHERE n.nspname = 'public' AND con.contype IN ('p','u','c','f') AND con.conislocal \
         ORDER BY \
           CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 ELSE 3 END, \
           rel.relname, con.conname",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog constraints: {e}")))?;
    Ok(rows)
}

async fn indexes(pool: &PgPool) -> Result<Vec<(String, String)>, BackupError> {
    let rows: Vec<(String, String)> = sqlx::query_as(
        "SELECT indexname, indexdef FROM pg_catalog.pg_indexes \
         WHERE schemaname = 'public' ORDER BY indexname",
    )
    .fetch_all(pool)
    .await
    .map_err(|e| BackupError::Export(format!("pg_catalog indexes: {e}")))?;
    Ok(rows)
}

#[cfg(test)]
mod tests {
    use std::io::Read;

    use super::*;

    #[test]
    fn identifier_quoting_is_postgres_exact() {
        assert_eq!(quote_ident("settings"), "settings");
        assert_eq!(quote_ident("settings_id_seq"), "settings_id_seq");
        assert_eq!(quote_ident("weird name"), "\"weird name\"");
        assert_eq!(quote_ident("Camel"), "\"Camel\"");
        assert_eq!(quote_ident("1col"), "\"1col\"");
        assert_eq!(quote_ident("a\"b"), "\"a\"\"b\"");
    }

    #[test]
    fn literal_quoting_escapes_single_quotes() {
        assert_eq!(quote_literal("plain"), "'plain'");
        assert_eq!(quote_literal("it's"), "'it''s'");
    }

    #[test]
    fn sequence_limits_render_like_pg_dump() {
        assert_eq!(limit("MINVALUE", i64::MIN), "NO MINVALUE");
        assert_eq!(limit("MAXVALUE", i64::MAX), "NO MAXVALUE");
        assert_eq!(limit("MINVALUE", 1), "MINVALUE 1");
        assert_eq!(limit("MAXVALUE", 99), "MAXVALUE 99");
    }

    #[test]
    fn gzip_of_an_empty_export_is_a_valid_gzip_member() {
        // Round-trip through the encoder without a database: the writer path
        // is the same one `export_gzip` uses.
        let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
        encoder.write_all(b"SELECT 1;\n").unwrap();
        let compressed = encoder.finish().unwrap();
        assert_eq!(&compressed[..2], &[0x1f, 0x8b], "gzip magic");
        let mut decoded = Vec::new();
        flate2::read::GzDecoder::new(&compressed[..])
            .read_to_end(&mut decoded)
            .unwrap();
        assert_eq!(decoded, b"SELECT 1;\n");
    }
}
